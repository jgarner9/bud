// Command gen-secret-rules writes the registry's secret pack (Suite D118):
// a curated subset of gitleaks' default rules, rendered as privacy_rules
// between the BEGIN and END secret rules markers of content/env/registry.jsonc.
// gitleaks is MIT licensed (Copyright (c) 2019 Zachary Rice); only its rule
// data is used, never its code.
//
//	curl -sSLo /tmp/gitleaks.toml https://raw.githubusercontent.com/gitleaks/gitleaks/<commit>/config/gitleaks.toml
//	go run ./scripts/gen-secret-rules /tmp/gitleaks.toml <commit> content/env/registry.jsonc
//
// To add a rule, add its gitleaks id to curated, run it again, and give the
// new rule samples in internal/registry's shipped rule tests.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

// curated are the gitleaks rules shipped: each a token with a fixed prefix
// or shape, so it rarely matches ordinary text. Rules that need a keyword
// nearby (generic-api-key and most vendors' ids) are left out, since a chat
// mentions "key" and "token" all the time. gitleaks' private-key rule is
// left out too: the registry has its own
var curated = []string{
	"1password-secret-key",
	"1password-service-account-token",
	"age-secret-key",
	"anthropic-admin-api-key",
	"anthropic-api-key",
	"aws-access-token",
	"digitalocean-pat",
	"doppler-api-token",
	"gcp-api-key",
	"github-app-token",
	"github-fine-grained-pat",
	"github-oauth",
	"github-pat",
	"github-refresh-token",
	"gitlab-pat",
	"hashicorp-tf-api-token",
	"huggingface-access-token",
	"jwt",
	"linear-api-key",
	"npm-access-token",
	"openai-api-key",
	"perplexity-api-key",
	"postman-api-token",
	"pypi-upload-token",
	"sendgrid-api-token",
	"shopify-access-token",
	"slack-app-token",
	"slack-bot-token",
	"slack-user-token",
	"slack-webhook-url",
	"stripe-access-token",
	"vault-service-token",
}

const (
	begin = "// BEGIN secret rules"
	end   = "// END secret rules"
)

type rule struct {
	id, regex string
	entropy   float64
	group     int
	keywords  []string
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "gen-secret-rules:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) != 3 {
		return fmt.Errorf("usage: gen-secret-rules <gitleaks.toml> <gitleaks commit> <registry.jsonc>")
	}
	src, err := os.ReadFile(args[0])
	if err != nil {
		return err
	}
	if !regexp.MustCompile(`^[0-9a-f]{40}$`).MatchString(args[1]) {
		return fmt.Errorf("the commit must be gitleaks' full 40-character commit id, so the source is pinned")
	}
	rules, err := parse(string(src))
	if err != nil {
		return err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s: generated by go run ./scripts/gen-secret-rules from gitleaks'\n", begin)
	fmt.Fprintf(&b, "    // config/gitleaks.toml at %s (MIT, Copyright (c) 2019\n", args[1])
	b.WriteString("    // Zachary Rice). Edit the list in scripts/gen-secret-rules, not these lines\n")
	for _, id := range curated {
		r, ok := rules[id]
		if !ok {
			return fmt.Errorf("gitleaks has no rule %q any more; drop it from curated", id)
		}
		if r.group > 1 {
			return fmt.Errorf("%s: secretGroup %d isn't supported; the router reads the first group", id, r.group)
		}
		if _, err := regexp.Compile(r.regex); err != nil {
			return fmt.Errorf("%s: the regex doesn't compile in Go: %w", id, err)
		}
		var re bytes.Buffer
		enc := json.NewEncoder(&re)
		enc.SetEscapeHTML(false)
		if err := enc.Encode(r.regex); err != nil {
			return err
		}
		fmt.Fprintf(&b, "    \"secret-%s\": { \"match\": %s, \"tier\": \"P0\"", id, strings.TrimSpace(re.String()))
		if r.entropy > 0 {
			fmt.Fprintf(&b, ", \"entropy\": %s", strconv.FormatFloat(r.entropy, 'f', -1, 64))
		}
		if len(r.keywords) > 0 {
			kw, err := json.Marshal(r.keywords)
			if err != nil {
				return err
			}
			fmt.Fprintf(&b, ", \"keywords\": %s", strings.ReplaceAll(string(kw), `","`, `", "`))
		}
		b.WriteString(" },\n")
	}
	b.WriteString("    " + end)

	reg, err := os.ReadFile(args[2])
	if err != nil {
		return err
	}
	text := string(reg)
	i, j := strings.Index(text, begin), strings.Index(text, end)
	if i < 0 || j < i {
		return fmt.Errorf("%s has no %q ... %q block inside privacy_rules to replace", args[2], begin, end)
	}
	out := text[:i] + b.String() + text[j+len(end):]

	return os.WriteFile(args[2], []byte(out), 0o644)
}

// parse reads the [[rules]] tables of gitleaks' TOML: their id, regex,
// entropy and secretGroup, ignoring allowlists and everything else
func parse(src string) (map[string]rule, error) {
	out := map[string]rule{}
	var cur *rule
	flush := func() {
		if cur != nil && cur.id != "" {
			out[cur.id] = *cur
		}
		cur = nil
	}
	inKeywords := false
	for n, line := range strings.Split(src, "\n") {
		line = strings.TrimSpace(line)
		if inKeywords {
			if line == "]" {
				inKeywords = false
				continue
			}
			kw, err := strconv.Unquote(strings.TrimSuffix(line, ","))
			if err != nil {
				return nil, fmt.Errorf("gitleaks.toml line %d (keywords): %w", n+1, err)
			}
			cur.keywords = append(cur.keywords, strings.ToLower(kw))
			continue
		}
		switch {
		case line == "[[rules]]":
			flush()
			cur = &rule{}
			continue
		case strings.HasPrefix(line, "["):
			if line != "[[rules]]" && cur != nil && cur.id != "" {
				flush() // an allowlist or another table ends the rule's own keys
			}
			continue
		case cur == nil:
			continue
		}
		key, val, ok := strings.Cut(line, " = ")
		if !ok {
			continue
		}
		var err error
		switch key {
		case "id":
			cur.id, err = strconv.Unquote(val)
		case "regex":
			v, found := strings.CutPrefix(val, "'''")
			v, closed := strings.CutSuffix(v, "'''")
			if !found || !closed {
				err = fmt.Errorf("only single-line ''' regexes are read")
			}
			cur.regex = v
		case "entropy":
			cur.entropy, err = strconv.ParseFloat(val, 64)
		case "secretGroup":
			cur.group, err = strconv.Atoi(val)
		case "keywords":
			if val == "[" {
				inKeywords = true
				break
			}
			// one line: ["a", "b"]
			var kws []string
			if err = json.Unmarshal([]byte(val), &kws); err == nil {
				for _, k := range kws {
					cur.keywords = append(cur.keywords, strings.ToLower(k))
				}
			}
		}
		if err != nil {
			return nil, fmt.Errorf("gitleaks.toml line %d (%s): %w", n+1, key, err)
		}
	}
	flush()

	return out, nil
}
